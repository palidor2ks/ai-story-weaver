-- Now insert question options for all 100 questions
-- Standard 5-point scale: Strongly Disagree (-10), Disagree (-5), Neutral (0), Agree (5), Strongly Agree (10), plus skip option
INSERT INTO question_options (id, question_id, text, value, display_order, is_skip_option)
SELECT
  q.id || '-opt-' || opt.idx,
  q.id,
  opt.text,
  opt.value,
  opt.idx,
  opt.is_skip
FROM questions q
CROSS JOIN (VALUES
  (1, 'Strongly Disagree', -10, false),
  (2, 'Disagree', -5, false),
  (3, 'Neutral', 0, false),
  (4, 'Agree', 5, false),
  (5, 'Strongly Agree', 10, false),
  (6, 'Not important to me', 0, true)
) AS opt(idx, text, value, is_skip)
WHERE q.topic_id LIKE 'local-%';
